#!/bin/bash
# add-incident-to-tracker.sh — append a verified incident to agent-incidents.ts and open a PR
# Called by the incident-tracker-pipeline cron
# Usage: echo '{"slug":"...","date":"...","tool":"...","headline":"..."...}' | bash add-incident-to-tracker.sh
#
# Validation guarantees:
#   1. JSON entry contains all required AgentIncident fields BEFORE insertion
#   2. Full-repo TypeScript check passes AFTER insertion
#   3. Production build passes (catches issues that tsc misses)
#   4. Branch is deleted and main is restored cleanly if any check fails
#
# Bot will NEVER open a PR that breaks the production build.
set -euo pipefail

SITE_REPO="/Users/moltbot/repos/permissionprotocol-site"
BRANCH="auto/incident-$(date +%Y%m%d-%H%M)"
SIGNAL_DATA=$(cat)

cd "$SITE_REPO"

# Required fields on AgentIncident (from src/data/agent-incidents.ts type def).
# If any are missing from the entry_ts string, fail fast with a clear message.
REQUIRED_FIELDS=(
  "slug"
  "date"
  "tool"
  "relevantGate"
  "platforms"
  "headline"
  "category"
  "severity"
)

# Pull the raw entry_ts string out of the JSON envelope. This is the TS literal
# that will be spliced into the array.
SIGNAL_ENTRY=$(echo "$SIGNAL_DATA" | jq -r '.entry_ts')

# Pre-flight: required-field check on the entry_ts string itself.
# We grep for "field:" since each field appears as a property in the TS literal.
MISSING_FIELDS=()
for field in "${REQUIRED_FIELDS[@]}"; do
  if ! echo "$SIGNAL_ENTRY" | grep -qE "^\s*${field}:\s" ; then
    MISSING_FIELDS+=("$field")
  fi
done

if [ ${#MISSING_FIELDS[@]} -gt 0 ]; then
  echo "ERROR: Required field(s) missing from incident entry: ${MISSING_FIELDS[*]}"
  echo "ERROR: Aborting — bot will not open a PR with a malformed incident."
  echo "ERROR: Fix the upstream entry_ts generator to include all required fields."
  exit 1
fi

# Ensure clean state
git fetch origin main 2>/dev/null
git checkout main 2>/dev/null
git pull origin main 2>/dev/null

# Create branch
git checkout -b "$BRANCH" 2>/dev/null

# Cleanup helper — used on any failure path to leave the local repo clean.
cleanup_and_abort() {
  local reason="$1"
  echo "ERROR: $reason"
  echo "ERROR: Reverting local state. Bot will not push or open a PR."
  git checkout main 2>/dev/null || true
  git branch -D "$BRANCH" 2>/dev/null || true
  exit 1
}

# Read current incidents file
INCIDENTS_FILE="src/data/agent-incidents.ts"
SLUG=$(echo "$SIGNAL_DATA" | jq -r '.slug')
HEADLINE=$(echo "$SIGNAL_DATA" | jq -r '.headline')

# Check slug doesn't already exist
if grep -q "slug: \"$SLUG\"" "$INCIDENTS_FILE"; then
  echo "SKIP: slug $SLUG already exists in agent-incidents.ts"
  git checkout main 2>/dev/null
  git branch -D "$BRANCH" 2>/dev/null
  exit 0
fi

# Write the new incident entry to a temp file
TEMP_ENTRY=$(mktemp)
echo "$SIGNAL_ENTRY" > "$TEMP_ENTRY"

# Find the closing array bracket and insert BEFORE it
CLOSE_LINE=$(grep -n "^];$" "$INCIDENTS_FILE" | head -1 | cut -d: -f1)
INSERT_LINE=$((CLOSE_LINE - 1))

# Insert the new entry BEFORE the closing bracket
sed -i '' "${INSERT_LINE}r ${TEMP_ENTRY}" "$INCIDENTS_FILE"
rm "$TEMP_ENTRY"

# Full-repo TypeScript check (NOT single file — single-file tsc misses cross-file
# type errors and was the gap that let two broken incidents land on main).
echo "Running full-repo tsc --noEmit ..."
if ! npx tsc --noEmit 2>&1; then
  cleanup_and_abort "TypeScript check failed. Incident entry has a type error."
fi

# Production build check — catches issues tsc misses (Next route conflicts, etc.)
echo "Running npm run build ..."
if ! npm run build 2>&1 | tail -20; then
  cleanup_and_abort "Production build failed. Incident entry breaks the site build."
fi

# All checks passed. Commit and push.
git add "$INCIDENTS_FILE"
git commit -m "auto: add incident — $HEADLINE

Scout-verified incident from signal scan.
Slug: $SLUG
Auto-generated by incident-tracker-pipeline.

Validated:
  - All required AgentIncident fields present
  - npx tsc --noEmit passes
  - npm run build passes"

git push origin "$BRANCH" 2>&1

# Create PR
PR_URL=$(gh pr create \
  --base main \
  --head "$BRANCH" \
  --title "Add incident: $HEADLINE" \
  --body "Automated addition from scout pipeline.

**Incident:** $HEADLINE
**Slug:** $SLUG

Validated by the bot before opening:
- ✅ All required AgentIncident fields present
- ✅ Full-repo TypeScript check passes
- ✅ Production build passes

Please review the incident data for accuracy before merging. Source links and coverage analysis are included in the entry." \
  2>&1)

echo "PR_URL=$PR_URL"

# Return to main
git checkout main 2>/dev/null
